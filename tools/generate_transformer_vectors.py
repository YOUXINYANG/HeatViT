INPUT_BASE = 0x00000000
WEIGHT_BASE = 0x01000000
SCRATCH_BASE = 0x02000000
OUTPUT_BASE = 0x03000000

IMAGE_BYTES = 224 * 224 * 3
W_BYTES = 768 * 192
BIAS_BYTES = 192 * 4
CLS_BYTES = 192
POS_BYTES = 197 * 192

OFF_W = 0
OFF_BIAS = W_BYTES
OFF_CLS = OFF_BIAS + BIAS_BYTES
OFF_POS = OFF_CLS + CLS_BYTES
WEIGHT_BYTES = OFF_POS + POS_BYTES

OFF_PATCH_MATRIX = 0
OFF_PATCH_EMBED = IMAGE_BYTES
OFF_ACT = OFF_PATCH_EMBED + 196 * 192
SCRATCH_BYTES = OFF_ACT + 197 * 192


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def pack_int8_bytes(values):
    byte_values = [int(v) & 0xFF for v in values]
    byte_values += [0xA5] * ((-len(byte_values)) % 8)
    words = []
    for i in range(0, len(byte_values), 8):
        word = 0
        for j in range(8):
            word |= byte_values[i + j] << (8 * j)
        words.append(word)
    return words


def pack_int32_bytes(values):
    byte_values = []
    for value in values:
        value = int(value) & 0xFFFFFFFF
        byte_values += [
            value & 0xFF,
            (value >> 8) & 0xFF,
            (value >> 16) & 0xFF,
            (value >> 24) & 0xFF,
        ]
    byte_values += [0xA5] * ((-len(byte_values)) % 8)
    words = []
    for i in range(0, len(byte_values), 8):
        word = 0
        for j in range(8):
            word |= byte_values[i + j] << (8 * j)
        words.append(word)
    return words


def write_mem(path, words):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="\n") as handle:
        for word in words:
            handle.write(f"{word:x}\n")


def write_manifest(outdir, seed, files, descriptors, out_scale):
    manifest = {
        "case": "patch",
        "seed": seed,
        "generator": "tools/generate_transformer_vectors.py",
        "image_bytes": IMAGE_BYTES,
        "weight_bytes": WEIGHT_BYTES,
        "scratch_bytes": SCRATCH_BYTES,
        "activation_offset": OFF_ACT,
        "activation_bytes": 197 * 192,
        "output_scale_exp": out_scale,
        "descriptors": [
            {"opcode": d.opcode, "hex": f"{d.pack():080x}"} for d in descriptors
        ],
        "files": files,
    }
    with open(outdir / "manifest.json", "w", newline="\n") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")


def write_sv_config(outdir, descriptors):
    lines = []
    lines.append("`ifndef PATCH_TB_CONFIG_PKG_SV")
    lines.append("`define PATCH_TB_CONFIG_PKG_SV")
    lines.append("")
    lines.append("// Generated by tools/generate_transformer_vectors.py; do not edit.")
    lines.append("package patch_tb_config_pkg;")
    lines.append("")
    lines.append(f"  localparam logic [31:0] INPUT_BASE   = 32'h{INPUT_BASE:08x};")
    lines.append(f"  localparam int          INPUT_BYTES  = {IMAGE_BYTES};")
    lines.append(f"  localparam logic [31:0] WEIGHT_BASE  = 32'h{WEIGHT_BASE:08x};")
    lines.append(f"  localparam int          WEIGHT_BYTES = {WEIGHT_BYTES};")
    lines.append(f"  localparam logic [31:0] SCRATCH_BASE = 32'h{SCRATCH_BASE:08x};")
    lines.append(f"  localparam int          SCRATCH_BYTES = {SCRATCH_BYTES};")
    lines.append(f"  localparam logic [31:0] OUTPUT_BASE  = 32'h{OUTPUT_BASE:08x};")
    lines.append("  localparam int          OUTPUT_BYTES = 0;")
    lines.append("")
    for idx, desc in enumerate(descriptors):
        lines.append(f"  localparam logic [319:0] DESC{idx} = 320'h{desc.pack():080x};")
    lines.append("")
    lines.append("  localparam logic signed [5:0] OUT_SCALE = -6'sd7;")
    lines.append(f"  localparam int ACT_OFFSET = {OFF_ACT};")
    lines.append("  localparam int ACT_BYTES  = 37824;")
    lines.append("")
    lines.append("  // Absolute access regions per descriptor for the memory-trace check.")
    trace = [
        ("D0", [(INPUT_BASE, IMAGE_BYTES), (SCRATCH_BASE, IMAGE_BYTES)]),
        (
            "D1",
            [
                (SCRATCH_BASE + OFF_PATCH_MATRIX, IMAGE_BYTES),
                (WEIGHT_BASE + OFF_W, W_BYTES),
                (WEIGHT_BASE + OFF_BIAS, BIAS_BYTES),
                (SCRATCH_BASE + OFF_PATCH_EMBED, 196 * 192),
            ],
        ),
        (
            "D2",
            [
                (SCRATCH_BASE + OFF_PATCH_EMBED, 196 * 192),
                (WEIGHT_BASE + OFF_POS, POS_BYTES),
                (WEIGHT_BASE + OFF_CLS, CLS_BYTES),
                (SCRATCH_BASE + OFF_ACT, 197 * 192),
            ],
        ),
    ]
    for prefix, regions in trace:
        for idx, (base, size) in enumerate(regions):
            lines.append(
                f"  localparam logic [31:0] {prefix}_R{idx}_BASE  = 32'h{base:08x};"
            )
            lines.append(f"  localparam int          {prefix}_R{idx}_BYTES = {size};")
    lines.append("")
    lines.append("endpackage")
    lines.append("")
    lines.append("`endif")

    config_path = REPO_ROOT / "sim" / "generated" / "patch_tb_config.sv"
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def generate_patch(seed, outdir):
    rng = np.random.default_rng(seed)
    image = rng.integers(-128, 128, size=224 * 224 * 3, dtype=np.int64)
    weight = rng.integers(-8, 8, size=(768, 192), dtype=np.int64)
    bias = rng.integers(-64, 64, size=192, dtype=np.int64)
    cls = rng.integers(-128, 128, size=192, dtype=np.int64)
    pos = rng.integers(-128, 128, size=(197, 192), dtype=np.int64)

    params = PatchParams(
        patch_weight=[list(row) for row in weight],
        patch_bias=[int(v) for v in bias],
        cls=[int(v) for v in cls],
        pos=[list(row) for row in pos],
    )
    activation = patch_embedding([int(v) for v in image], params)

    descriptors = [
        Descriptor(
            opcode=OP_PATCHIFY,
            flags=1 << FLAG_SRC0_INPUT,
            m=196,
            n=768,
            src0_offset=0,
            dst_offset=OFF_PATCH_MATRIX,
            src0_scale_exp=-7,
            dst_scale_exp=-7,
        ),
        Descriptor(
            opcode=OP_GEMM,
            flags=1 << FLAG_BIAS_ENABLE,
            m=196,
            n=192,
            k=768,
            src0_offset=OFF_PATCH_MATRIX,
            src1_offset=OFF_W,
            bias_offset=OFF_BIAS,
            dst_offset=OFF_PATCH_EMBED,
            src0_scale_exp=-7,
            src1_scale_exp=-7,
            dst_scale_exp=-7,
        ),
        Descriptor(
            opcode=OP_COPY_ADD_POS,
            flags=1 << FLAG_AUX_WEIGHT,
            m=197,
            n=192,
            src0_offset=OFF_PATCH_EMBED,
            src1_offset=OFF_POS,
            aux_offset=OFF_CLS,
            dst_offset=OFF_ACT,
            src0_scale_exp=-7,
            src1_scale_exp=-7,
            aux_scale_exp=-7,
            dst_scale_exp=-7,
        ),
    ]

    image_path = outdir / "image.mem"
    write_mem(image_path, pack_int8_bytes([int(v) for v in image]))

    weight_bytes = []
    weight_bytes += [int(v) for v in weight.ravel()]
    weight_bytes += [0] * ((-len(weight_bytes)) % 8)
    weight_words = pack_int8_bytes(weight_bytes)[:]  # W block, then bias/cls/pos
    bias_words = pack_int32_bytes([int(v) for v in bias])
    cls_words = pack_int8_bytes([int(v) for v in cls])
    pos_words = pack_int8_bytes([int(v) for v in pos.ravel()])
    weight_path = outdir / "weight.mem"
    write_mem(weight_path, weight_words + bias_words + cls_words + pos_words)

    expected_path = outdir / "expected.mem"
    write_mem(expected_path, pack_int8_bytes(
        [v for row in activation for v in row]))

    write_sv_config(outdir, descriptors)

    files = [
        {
            "name": "image.mem",
            "records": len(pack_int8_bytes([int(v) for v in image])),
            "sha256": sha256_file(image_path),
        },
        {
            "name": "weight.mem",
            "records": len(weight_words) + len(bias_words) + len(cls_words) + len(pos_words),
            "sha256": sha256_file(weight_path),
        },
        {
            "name": "expected.mem",
            "records": len(pack_int8_bytes([v for row in activation for v in row])),
            "sha256": sha256_file(expected_path),
        },
    ]
    write_manifest(outdir, seed, files, descriptors, -7)


def align8(value):
    return (value + 7) & ~7


def _flag(*bits):
    value = 0
    for bit in bits:
        value |= 1 << bit
    return value


