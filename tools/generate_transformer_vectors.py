def generate_block(seed, tokens, outdir):
    rng = np.random.default_rng(seed)
    n = tokens
    if n < 2 or n > 197:
        raise ValueError("tokens must be in [2, 197]")

    x = [
        [int(v) for v in row]
        for row in rng.integers(-128, 128, size=(n, 192), dtype=np.int64)
    ]
    params0 = _random_block_params(rng)
    params1 = _random_block_params(rng)
    z0, ck0 = transformer_block(x, params0)
    z1, ck1 = transformer_block(z0, params1)

    z_rows = (n + 7) // 8 * 8
    scratch0 = _block_scratch_offsets(n, 0, z_rows)
    scratch1 = _block_scratch_offsets(
        n, scratch0["z"] + scratch0["z_rows_bytes"], z_rows
    )
    scratch1["x"] = scratch0["z"]
    scratch_bytes = align8(scratch1["z"] + scratch1["z_rows_bytes"])

    weight_offsets, weight_bytes = _block_weight_offsets()
    weight_names = (
        "wqkv", "bqkv", "wproj", "bproj", "gamma1", "beta1",
        "w1", "b1", "w2", "b2", "gamma2", "beta2",
    )
    weight0 = {name: weight_offsets[f"{name}0"] for name in weight_names}
    weight1 = {name: weight_offsets[f"{name}1"] for name in weight_names}

    descriptors = (
        _block_descriptors(n, scratch0, weight0)
        + _block_descriptors(n, scratch1, weight1)
    )
    regions = (
        _block_regions(n, scratch0, weight0, z_rows)
        + _block_regions(n, scratch1, weight1, z_rows)
    )

    offsets = {
        "x0_off": scratch0["x"],
        "ln1_0_off": scratch0["ln1"],
        "msa_0_off": scratch0["msa"],
        "y_0_off": scratch0["y"],
        "ln2_0_off": scratch0["ln2"],
        "hidden_0_off": scratch0["hidden"],
        "ffn_out_0_off": scratch0["ffn_out"],
        "z0_off": scratch0["z"],
        "x1_off": scratch1["x"],
        "ln1_1_off": scratch1["ln1"],
        "msa_1_off": scratch1["msa"],
        "y_1_off": scratch1["y"],
        "ln2_1_off": scratch1["ln2"],
        "hidden_1_off": scratch1["hidden"],
        "ffn_out_1_off": scratch1["ffn_out"],
        "z1_off": scratch1["z"],
        "scratch_bytes": scratch_bytes,
        "weight_bytes": weight_bytes,
    }
    write_block_sv_config(outdir, tokens, offsets, descriptors, regions)

    x_path = outdir / "input.mem"
    write_mem(x_path, pack_int8_bytes([v for row in x for v in row]))

    weight_parts = []
    for params in (params0, params1):
        weight_parts += [
            pack_int8_bytes([v for row in params.mhsa.wqkv for v in row]),
            pack_int32_bytes(params.mhsa.bqkv),
            pack_int8_bytes([v for row in params.mhsa.wproj for v in row]),
            pack_int32_bytes(params.mhsa.bproj),
            pack_int8_bytes(params.mhsa.ln_gamma),
            pack_int8_bytes(params.mhsa.ln_beta),
            pack_int8_bytes([v for row in params.ffn.w1 for v in row]),
            pack_int32_bytes(params.ffn.b1),
            pack_int8_bytes([v for row in params.ffn.w2 for v in row]),
            pack_int32_bytes(params.ffn.b2),
            pack_int8_bytes(params.ffn.ln_gamma),
            pack_int8_bytes(params.ffn.ln_beta),
        ]
    weight_path = outdir / "weight.mem"
    weight_words = [word for part in weight_parts for word in part]
    write_mem(weight_path, weight_words)

    descriptors_path = outdir / "descriptors.mem"
    write_descriptors_mem(descriptors_path, descriptors)

    checkpoint_names = ("ln1", "msa", "y", "ln2", "hidden", "ffn_out", "z")
    checkpoint_paths = {}
    for block, (z_out, ck) in ((0, (z0, ck0)), (1, (z1, ck1))):
        for name in checkpoint_names:
            flat = [v for row in ck[name] for v in row]
            if name == "z":
                flat += [0xA5] * (192 * (z_rows - n))
            path = outdir / f"b{block}_{name}_expected.mem"
            checkpoint_paths[f"b{block}_{name}"] = path
            write_mem(path, pack_int8_bytes(flat))

    files = [
        {
            "name": "input.mem",
            "records": len(pack_int8_bytes([v for row in x for v in row])),
            "sha256": sha256_file(x_path),
        },
        {"name": "weight.mem", "records": len(weight_words),
         "sha256": sha256_file(weight_path)},
        {"name": "descriptors.mem", "records": len(descriptors),
         "sha256": sha256_file(descriptors_path)},
    ]
    files += [
        {"name": path.name, "records": 0, "sha256": sha256_file(path)}
        for path in checkpoint_paths.values()
    ]
    manifest = {
        "case": "block",
        "seed": seed,
        "tokens": tokens,
        "generator": "tools/generate_transformer_vectors.py",
        "weight_bytes": weight_bytes,
        "scratch_bytes": scratch_bytes,
        "z_rows": z_rows,
        "scales": {"activation": -7, "weight": 0},
        "descriptors": [
            {"opcode": d.opcode, "hex": f"{d.pack():080x}"} for d in descriptors
        ],
        "files": files,
    }
    with open(outdir / "manifest.json", "w", newline="\n") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", required=True,
                        choices=["patch", "mhsa", "ffn", "block"])
    parser.add_argument("--tokens", type=int, default=197)
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    outdir = args.output
    if not outdir.is_absolute():
        outdir = REPO_ROOT / outdir
    if args.case == "patch":
        generate_patch(args.seed, outdir)
    elif args.case == "mhsa":
        generate_mhsa(args.seed, args.tokens, outdir)
    elif args.case == "ffn":
        generate_ffn(args.seed, args.tokens, outdir)
    else:
        generate_block(args.seed, args.tokens, outdir)
    print(f"generated {args.case} vectors -> {outdir}")


if __name__ == "__main__":
    main()
